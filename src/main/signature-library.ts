/**
 * The signature library's rules, free of Electron and the file system so
 * they can be tested: checking uploaded PNGs and changing the index.
 */

import type { SignatureKind } from '../shared/api'

/** What `index.json` holds per entry; the PNG is `<id>.png` next to it. */
export interface IndexEntry {
  id: string
  kind: SignatureKind
  name: string
  isDefault: boolean
  width: number
  height: number
  createdAt: string
}

export const MAX_PNG_BYTES = 5 * 1024 * 1024
export const MAX_NAME_LENGTH = 80

const PNG_SIGNATURE = [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]

export function isSignatureKind(value: unknown): value is SignatureKind {
  return value === 'signature' || value === 'initials'
}

/** The pixel size of a PNG, or null if `bytes` is not one. */
export function pngSize(bytes: Uint8Array): { width: number; height: number } | null {
  if (bytes.length < 24) return null
  if (PNG_SIGNATURE.some((value, index) => bytes[index] !== value)) return null
  // The first chunk must be IHDR: width and height are its first 8 bytes.
  if (String.fromCharCode(...bytes.slice(12, 16)) !== 'IHDR') return null
  const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength)
  const width = view.getUint32(16)
  const height = view.getUint32(20)
  return width > 0 && height > 0 ? { width, height } : null
}

export function cleanName(value: unknown, fallback: string): string {
  const text = typeof value === 'string' ? value.replace(/\s+/g, ' ').trim() : ''
  return (text || fallback).slice(0, MAX_NAME_LENGTH)
}

/** Ids are generated by main; anything else is refused (they name files). */
export function isEntryId(value: unknown): value is string {
  return typeof value === 'string' && /^[a-f0-9-]{8,64}$/.test(value)
}

/** The index with `id` the only default of its kind. */
export function withDefault(entries: IndexEntry[], id: string): IndexEntry[] {
  const target = entries.find((entry) => entry.id === id)
  if (!target) return entries
  return entries.map((entry) =>
    entry.kind === target.kind ? { ...entry, isDefault: entry.id === id } : entry
  )
}

/** Adds an entry; the first of its kind becomes the default. */
export function withAdded(entries: IndexEntry[], entry: IndexEntry): IndexEntry[] {
  const first = !entries.some((candidate) => candidate.kind === entry.kind)
  return [...entries, { ...entry, isDefault: first }]
}

/** Removes an entry; if it was the default, the newest remaining one takes over. */
export function withRemoved(entries: IndexEntry[], id: string): IndexEntry[] {
  const removed = entries.find((entry) => entry.id === id)
  const rest = entries.filter((entry) => entry.id !== id)
  if (!removed?.isDefault) return rest
  const heir = [...rest].reverse().find((entry) => entry.kind === removed.kind)
  return heir ? withDefault(rest, heir.id) : rest
}

/** Reads `index.json`, dropping anything malformed. */
export function parseIndex(text: string): IndexEntry[] {
  let value: unknown
  try {
    value = JSON.parse(text)
  } catch {
    return []
  }
  if (!Array.isArray(value)) return []
  return value.filter(
    (entry): entry is IndexEntry =>
      typeof entry === 'object' &&
      entry !== null &&
      isEntryId((entry as IndexEntry).id) &&
      isSignatureKind((entry as IndexEntry).kind) &&
      typeof (entry as IndexEntry).name === 'string' &&
      typeof (entry as IndexEntry).width === 'number' &&
      typeof (entry as IndexEntry).height === 'number'
  )
}

"""The FastAPI application.

Conventions (see docs/plan/phase-1-foundation.md):
- everything lives under ``/v1`` and requires the ``X-Engine-Token`` header;
- JSON in and out with camelCase field names;
- errors are ``{"error": {"code": ..., "message": ...}}``.
"""

import secrets
import sys

import pymupdf
from fastapi import APIRouter, Depends, FastAPI, Request
from fastapi.middleware.cors import CORSMiddleware

from . import __version__
from .errors import UnauthorizedError, install_error_handlers
from .sessions import SessionRegistry

TOKEN_HEADER = "X-Engine-Token"


def create_app(token: str, allowed_origins: list[str] | None = None) -> FastAPI:
    """Build the engine app.

    ``token`` is the shared secret generated by the Electron main process.
    ``allowed_origins`` are the renderer origins permitted by CORS.
    """
    if not token:
        raise ValueError("An engine token is required.")

    def require_token(request: Request) -> None:
        supplied = request.headers.get(TOKEN_HEADER, "")
        if not secrets.compare_digest(supplied.encode(), token.encode()):
            raise UnauthorizedError()

    app = FastAPI(
        title="PDFnix engine",
        version=__version__,
        docs_url=None,
        redoc_url=None,
        openapi_url=None,
    )
    app.state.sessions = SessionRegistry()
    install_error_handlers(app)

    # CORS preflight requests carry no token, so the middleware answers them
    # before routing. The token, not the origin, is what protects the API.
    app.add_middleware(
        CORSMiddleware,
        allow_origins=allowed_origins or [],
        allow_methods=["*"],
        allow_headers=[TOKEN_HEADER, "Content-Type"],
        max_age=600,
    )

    v1 = APIRouter(prefix="/v1", dependencies=[Depends(require_token)])

    @v1.get("/health")
    def health() -> dict[str, str | int]:
        return {
            "status": "ok",
            "engineVersion": __version__,
            "pymupdfVersion": pymupdf.__version__,
            "mupdfVersion": pymupdf.mupdf_version,
            "pythonVersion": sys.version.split()[0],
            "openDocuments": len(app.state.sessions),
        }

    app.include_router(v1)
    return app
